-- Policies for "registrations" table
-- 1. Allow public checkout inserts (anonymous students checkout before being logged in)
CREATE POLICY "Allow anonymous checkout inserts" 
  ON registrations FOR INSERT 
  TO anon, service_role 
  WITH CHECK (true);

-- 2. Allow SELECT and UPDATE operations for backend API queries using publishable/service keys
CREATE POLICY "Allow select registrations for backend" 
  ON registrations FOR SELECT 
  TO anon, service_role 
  USING (true);

CREATE POLICY "Allow update registrations for backend" 
  ON registrations FOR UPDATE 
  TO anon, service_role 
  USING (true)
  WITH CHECK (true);

-- Policies for "settings" table
-- 1. Allow SELECT queries for password checks
CREATE POLICY "Allow select settings for auth check" 
  ON settings FOR SELECT 
  TO anon, service_role 
  USING (true);

-- 2. Allow UPDATE queries for password settings changes
CREATE POLICY "Allow update settings for password change" 
  ON settings FOR UPDATE 
  TO anon, service_role 
  USING (true)
  WITH CHECK (true);


