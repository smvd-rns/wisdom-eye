-- Run this SQL in your Supabase SQL Editor to create the tables.
-- It will store student enrollment data, payment tokens, shipping parcel addresses, and settings.

-- 1. registrations table
CREATE TABLE IF NOT EXISTS registrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  mobile TEXT NOT NULL,
  delivery_type TEXT NOT NULL, -- 'pickup' or 'delivery'
  address TEXT,
  city TEXT,
  state TEXT,
  pincode TEXT,
  amount_paid NUMERIC NOT NULL,
  razorpay_order_id TEXT UNIQUE,
  razorpay_payment_id TEXT UNIQUE,
  payment_status TEXT DEFAULT 'pending', -- 'pending', 'paid', 'failed'
  graphy_status TEXT DEFAULT 'pending', -- 'pending', 'success', 'failed'
  shipping_status TEXT DEFAULT 'not_applicable', -- 'not_applicable', 'pending_shipment', 'shipped'
  tracking_id TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. settings table
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

